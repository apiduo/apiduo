/** JSON templates; `json` on a client picks one of these. */
export function jsonTemplate(kind: 'std' | 'vscode', url: string) {
  const auth = `Bearer ${TOKEN_SLOT}`
  const root = kind === 'vscode' ? 'servers' : 'mcpServers'
  return `{
  "${root}": {
    "apiduo": {
      "type": "http",
      "url": "${url}",
      "headers": {
        "Authorization": "${auth}"
      }
    }
  }
}`
}

/** 品牌标：路径数据 + 固定 viewBox，尺寸由调用方给。 */
export function Mark({
  id,
  className,
}: {
  id: string
  className?: string
}) {
  return (
    <svg
      viewBox='0 0 24 24'
      fill='currentColor'
      aria-hidden='true'
      className={className}
    >
      {MARK_PATHS[id]}
    </svg>
  )
}

