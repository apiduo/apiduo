export const NAV_APP_ICON_OPTIONS = Object.keys(NAV_APP_ICONS).sort()

export function navAppIcon(name: string | undefined): LucideIcon {
  if (!name) return Globe
  return NAV_APP_ICONS[name] ?? Globe
}
